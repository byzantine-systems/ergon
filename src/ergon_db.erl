-doc """
Application-time time travel: the job versions whose `valid_period` contained
`Instant`, i.e. the truth about the world as of that moment.
""".
-spec jobs_asof(pg_timestamp()) -> {ok, [job()]} | {error, db_error()}.
jobs_asof(Instant) ->
    maybe
        {ok, #{rows := Rows}} ?= ergon_sql:query({jobs, asof}, [Instant]),
        {ok, decode_jobs(Rows)}
    end.

-doc """
System-time time travel: what the database believed about each job as of
`Instant`, spanning live rows and the archived `ergon.jobs_history` twin.
""".
-spec jobs_asof_system(pg_timestamp()) -> {ok, [job()]} | {error, db_error()}.
jobs_asof_system(Instant) ->
    maybe
        {ok, #{rows := Rows}} ?= ergon_sql:query({jobs, asof_system}, [Instant]),
        {ok, decode_jobs(Rows)}
    end.

%% ---------------
%% Helpers
%% ---------------

%% A row that does not match `from_row/1`'s eleven columns means a statement has
%% drifted from `ergon_job:column_list/0`. That must raise rather than be skipped,
%% because a silently shortened list reads as an empty queue. `from_row/1` has a
%% single clause over an eleven-element tuple, so the drift surfaces as a
%% `function_clause` on the first bad row; the generator does no filtering.
decode_jobs(Rows) -> [ergon_job:from_row(Row) || Row <- Rows].

first_row([Row | _Rest], _WhenEmpty) -> {ok, ergon_job:from_row(Row)};
first_row([], WhenEmpty) -> {error, WhenEmpty}.

%% Read per call rather than cached at boot, so a running node picks up a change
%% to the strategy without a restart. It is three proplist lookups on a retry
%% path that is already doing a round trip.
-spec retry_backoff() -> {retry_backoff_strategy(), pos_integer(), pos_integer()}.
retry_backoff() ->
    Env = proplists:get_value(retry_backoff, application:get_env(ergon, ?MODULE, []), []),
    {
        proplists:get_value(strategy, Env, ?DEFAULT_BACKOFF_STRATEGY),
        proplists:get_value(base_ms, Env, ?DEFAULT_BACKOFF_BASE_MS),
        proplists:get_value(cap_ms, Env, ?DEFAULT_BACKOFF_CAP_MS)
    }.

%% Clause-matched rather than defaulted, so a typo in sys.config fails loudly at
%% the first retry instead of quietly selecting a strategy nobody asked for. The
%% SQL function's own fallback is full_jitter, which no value reaching it from
%% here can trigger.
-spec strategy_to_binary(retry_backoff_strategy()) -> binary().
strategy_to_binary(full_jitter) -> ~"full_jitter";
strategy_to_binary(equal_jitter) -> ~"equal_jitter";
strategy_to_binary(none) -> ~"none".
